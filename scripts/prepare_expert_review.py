#!/usr/bin/env python3
"""Write the committed review files for the silver-sample and grammarian checks.

Reads a silver extraction directory (examples.jsonl, review_sample.jsonl) and
writes, into data/reviews/:

- silver_sample.jsonl: the 200 review items, with only what a reviewer needs;
- silver_overlap_ids.json: the seeded subset the grammarian checks blind;
- uncovered_examples.jsonl: extracted boundaries that no rule generates;

Data files are SLP1, like everything internal (protocol amendment 0.6). Only
what people read is IAST: GRAMMARIAN_CHECKS.md here, and the worksheets, which
scripts/build_review_page.py converts when it builds them.
- GRAMMARIAN_CHECKS.md: the three short checks of issue #66;
- manifest.json: input hashes, the seed and output hashes.
"""

import argparse
import hashlib
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from panini.dcs import COMPOUND_PREFIXES
from panini.lexicon import FINAL_VARIANTS
from panini.translit import slp1_to_iast
from build_review_page import iast_item


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_jsonl(path):
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_jsonl(path, rows):
    path.write_text("".join(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n" for r in rows), encoding="utf-8")


def review_item(row):
    """Only what the reviewer judges: the sentence, the span and the proposed split (SLP1)."""
    sentence, (start, end) = row["source_sentence"], row["source_span"]
    if sentence[start:end] != row["source_surface"]:
        raise ValueError(f"{row['example_id']}: source_span does not match source_surface")
    return {
        "item_id": row["example_id"],
        "sentence": sentence.rstrip(),
        "span": [start, end],
        "surface": row["source_surface"],
        "proposed_left": row["left"],
        "proposed_right": row["right"],
        "left_lemma": row["left_lemma"],
        "right_lemma": row["right_lemma"],
    }


def overlap_ids(items, size, seed):
    ids = sorted(item["item_id"] for item in items)
    return sorted(random.Random(seed).sample(ids, size))


def grammarian_checks(uncovered):
    uncovered = [iast_item(r) for r in uncovered]
    variants = "\n".join(f"| -{slp1_to_iast(k)} | {', '.join('-' + slp1_to_iast(v) for v in vs)} | |"
                         for k, vs in FINAL_VARIANTS.items())
    prefixes = "\n".join(f"| {p} | |" for p in sorted(slp1_to_iast(p) for p in COMPOUND_PREFIXES))
    examples = "\n".join(
        f"| {i} | {r['item_id']} | {r['surface']} | {r['proposed_left']} + {r['proposed_right']} | {r['sentence']} | |"
        for i, r in enumerate(uncovered, 1))
    return f"""# Grammarian Checks (issue #66)

Generated by `scripts/prepare_expert_review.py`; do not edit the tables' left
columns. Fill in the last column of each table, then commit this file on the
branch `review/grammarian-checks`, or paste the answers into issue #66.

Transliteration is IAST.

## 1. Compound prefixes

When the boundary extractor meets one of these DCS lemmas at the start of a
word, it treats the word as a compound member, not as a separate word, so the
junction is not counted as external sandhi. Is each entry right? Add any
missing prefix as a new row.

| Lemma | Correct as a compound prefix? (yes / no, with a note) |
| --- | --- |
{prefixes}

## 2. Word-final normalisation

A word taken from a sentence keeps its sandhi-changed final sound. Before the
dictionary lookup we also try the pausal forms below. The table lists, for a
final sound, the pausal finals we try. Two further rules apply: a word ending
in -o also tries -as, and a word ending in -a or -ā also tries -as or -ās (the
visarga lost before a vowel).

The aim is "could this be a real word", so being generous is acceptable;
missing variants matter more than extra ones.

| Final as found | Pausal finals tried | Wrong or missing? |
| --- | --- | --- |
{variants}

## 3. Boundaries no rule generates

These {len(uncovered)} boundaries were extracted from the corpus, but none of the 18
draft rules produces the fused form from the proposed split. For each, choose:

- **rule**: a real sandhi that a rule should cover (name the sūtra if you can);
- **variant**: an optional, archaic or editorial variant we may leave out;
- **error**: the text or the split is wrong.

| # | Item | Fused form | Proposed split | Sentence | rule / variant / error, with a note |
| --- | --- | --- | --- | --- | --- |
{examples}
"""


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--silver", type=Path, default=ROOT / "data/processed/dcs-silver-v2")
    p.add_argument("--output", type=Path, default=ROOT / "data/reviews")
    p.add_argument("--overlap", type=int, default=50)
    p.add_argument("--seed", type=int, default=2026)
    args = p.parse_args()

    sample_path, examples_path = args.silver / "review_sample.jsonl", args.silver / "examples.jsonl"
    items = [review_item(r) for r in read_jsonl(sample_path)]
    uncovered = [review_item(r) for r in read_jsonl(examples_path) if r["rule_id"] == "UNSUPPORTED"]
    if args.overlap > len(items):
        p.error("overlap is larger than the sample")

    out = args.output
    out.mkdir(parents=True, exist_ok=True)
    write_jsonl(out / "silver_sample.jsonl", items)
    (out / "silver_overlap_ids.json").write_text(
        json.dumps(overlap_ids(items, args.overlap, args.seed), indent=1) + "\n", encoding="utf-8")
    write_jsonl(out / "uncovered_examples.jsonl", uncovered)
    (out / "GRAMMARIAN_CHECKS.md").write_text(grammarian_checks(uncovered), encoding="utf-8")

    written = ["silver_sample.jsonl", "silver_overlap_ids.json", "uncovered_examples.jsonl", "GRAMMARIAN_CHECKS.md"]
    manifest = {
        "source": "DCS_pick (Krishna et al. 2017, CC BY 4.0), silver extraction by scripts/extract_dcs_boundaries.py",
        "inputs": {"review_sample.jsonl": sha256(sample_path), "examples.jsonl": sha256(examples_path)},
        "overlap": {"size": args.overlap, "seed": args.seed},
        "outputs": {name: sha256(out / name) for name in written},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"{len(items)} items, {args.overlap} overlap, {len(uncovered)} uncovered -> {out}")


if __name__ == "__main__":
    main()
